def to_simp(text):
    return cc_t2s.convert(text)

def is_poetry_line(line):
    """判断是否为诗词/韵文行（保持原文）"""
    if re.match(r'^[诗|词|赋|古风|偈|歌|曲|有诗为证|诗曰|词曰|偈曰|古风曰|古风一首|绝句|律诗]', line):
        return True
    if re.match(r'^[《\[【]', line):
        return True
    return False

def baihua_transform(text):
    """白话文：保留诗词，正文用短语级替换"""
    lines = text.split("\n")
    out = []
    for ln in lines:
        stripped = ln.strip()
        if not stripped:
            out.append(ln)
            continue
        # 标题行、诗词行保留
        if stripped.startswith("第") and ("回" in stripped[:10] or "回" in stripped[:6]):
            out.append(ln)
            continue
        if is_poetry_line(stripped):
            out.append(ln)
            continue
        # 但见/但见得/有诗为证块之后的韵文也保留 - 简化：直接应用规则
        result = ln
        for old, new in BAI_RULES:
            result = result.replace(old, new)
        out.append(result)
    return "\n".join(out)

def rebuild_jian_bai(version_id):
    ver_dir = os.path.join(VERSIONS_DIR, version_id)
    fan_dir = os.path.join(ver_dir, "fan")
    jian_dir = os.path.join(ver_dir, "jian")
    bai_dir = os.path.join(ver_dir, "bai")
    
    # 清空旧目录
    for d in [jian_dir, bai_dir]:
        if os.path.exists(d):
            shutil.rmtree(d)
        os.makedirs(d, exist_ok=True)
    
    # 读chapters.json
    with open(os.path.join(ver_dir, "chapters.json"), "r", encoding="utf-8") as f:
        chs = json.load(f)
    
    for ch in chs:
        fname = os.path.basename(ch["file"])
        fan_path = os.path.join(fan_dir, fname)
        with open(fan_path, "r", encoding="utf-8") as f:
            text = f.read()
        
        # 简体
        jian_text = to_simp(text)
        with open(os.path.join(jian_dir, fname), "w", encoding="utf-8") as f:
            f.write(jian_text)
        
        # 白话：先转简体再应用白话规则（韵文保留繁体转简后的样子，其余替换）
        bai_text = baihua_transform(jian_text)
        with open(os.path.join(bai_dir, fname), "w", encoding="utf-8") as f:
            f.write(bai_text)
    
    # 写 index.json
    index = {
        "version": version_id,
        "chapters_count": len(chs),
        "has_prologue": chs[0]["num"] == 0 if chs else False,
    }
    with open(os.path.join(ver_dir, "index.json"), "w", encoding="utf-8") as f:
        json.dump(index, f, ensure_ascii=False, indent=2)
    
    return len(chs)

def main():
    versions = ["jinshengtan", "v70", "jin70", "jin70_pi", "v100", "v120", "jiqin"]
    # jiqin（冀勤校注）基于v100的fan
    # 先处理已重建fan的版本
    for vid in ["jinshengtan", "v70", "jin70", "jin70_pi", "v100", "v120"]:
        n = rebuild_jian_bai(vid)
        print(f"✅ {vid}: jian+bai 重建完成（{n}文件）")
    
    # jiqin 以v100为底本
    jiqin_dir = os.path.join(VERSIONS_DIR, "jiqin")
    if os.path.exists(jiqin_dir):
        # 复制v100的fan/jian/bai到jiqin（如果jiqin fan不是自己的）
        for sub in ["fan", "jian", "bai"]:
            src = os.path.join(VERSIONS_DIR, "v100", sub)
            dst = os.path.join(jiqin_dir, sub)
            if os.path.exists(dst):
                shutil.rmtree(dst)
            shutil.copytree(src, dst)
        shutil.copy2(
            os.path.join(VERSIONS_DIR, "v100", "chapters.json"),
            os.path.join(jiqin_dir, "chapters.json"))
        print("✅ jiqin: 复制v100三语体")

if __name__ == "__main__":
    main()
