RULES.sort(key=lambda x:-len(x[0]))
_alt = "|".join(re.escape(k) for k,_ in RULES)
_map = dict(RULES)
_rx = re.compile("(" + _alt + ")")

def is_title(s):
    return bool(re.match(r'^第[一二三四五六七八九十百零〇两]+回', s)) or s.startswith('引首') or s.startswith('楔子')
def is_verse(s):
    if not s.strip() or is_title(s): return False
    if re.search(r'(说道|问道|答道|叫道|喝道|唤道|道：|道:|道“|道")', s): return False
    parts=[p for p in re.split(r'[，。；：！？、,]', s) if p.strip()]
    if len(parts)<2: return False
    return max(len(p) for p in parts)<=8

def bai(text):
    out=[]
    for ln in text.split("\n"):
        s=ln.strip()
        if not s or is_title(s) or is_verse(s):
            out.append(ln); continue
        r=_rx.sub(lambda m:_map[m.group(1)], ln)
        # 叠字回缩：白话中出现的叠字若原句没有，判为规则碰撞产物
        def _fix(m):
            run=m.group(0)
            return run if run in ln else m.group(1)
        r=re.sub(r'([\u4e00-\u9fff])\1+', _fix, r)
        out.append(r)
    return "\n".join(out)

