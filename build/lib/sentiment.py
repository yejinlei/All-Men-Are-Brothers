def _count(text, lex):
    c = 0
    for w, wt in lex.items():
        n = text.count(w)
        if n:
            c += n * wt
    return c


def score(text: str) -> dict:
    """对一段文本打分。返回 pos/neg/aro 计数与 polarity/arousal 指标。"""
    t = tu.strip_note_markers(text or '')
    nchar = len(tu.cjk_only(t))
    pos = _count(t, POS)
    neg = _count(t, NEG)
    aro = _count(t, ARO)
    polarity = (pos - neg) / (pos + neg + 1.0)
    arousal = aro / (nchar / 1000.0) if nchar else 0.0
    return {'nchar': nchar, 'pos': pos, 'neg': neg, 'aro': aro,
            'polarity': round(polarity, 4), 'arousal': round(arousal, 3)}
